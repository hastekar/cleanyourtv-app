import { createRequire } from 'node:module';
import { preview } from 'vite';
const { chromium, devices } = createRequire(import.meta.url)('playwright');
const out = process.argv[2];
const server = await preview({ preview: { port: 4872, strictPort: true }, logLevel: 'silent' });
const b = await chromium.launch();
const ctx = await b.newContext({ ...devices['Pixel 7'], locale: 'tr-TR' });
const p = await ctx.newPage();
p.on('console', (m) => m.type() === 'error' && console.log('ERR', m.text()));
p.on('pageerror', (e) => console.log('PAGEERR', String(e)));
await p.goto('http://localhost:4872/?e2e');
await p.screenshot({ path: `${out}/01-loading.png` });
await p.waitForSelector('.home:not([hidden])');
await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/02-home.png` });
await p.click('.play.huge', { force: true }); await p.waitForTimeout(350);
await p.screenshot({ path: `${out}/03-prelevel.png` });
await p.click('.pick', { force: true }); await p.click('.sheet .play', { force: true }); await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/04-howto.png` });
await p.click('.sheet .play', { force: true }); await p.waitForTimeout(400);
await p.screenshot({ path: `${out}/05-game.png` });
await p.click('.game .round', { force: true }); await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/06-pause.png` });
await p.click('.sheet .col .plain:last-child', { force: true }); await p.waitForTimeout(300);
await p.click('.topbar .coins', { force: true }); await p.waitForTimeout(350);
await p.screenshot({ path: `${out}/07-shop.png`, fullPage: false });
await b.close(); await server.close();
